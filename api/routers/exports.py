@router.post("/message/{message_id}")
async def export_message_pdf(
    message_id: str,
    request: Request,
    user = Depends(get_clerk_auth().optional_auth),
    export_type: str = "free"  # "free", "gamma_pdf", "gamma_pptx"
):
    """
    Export a single chat message as a professional document.

    Export types:
    - "free": Institutional-style PDF via Playwright (default)
    - "gamma_pdf": Gamma API presentation as PDF (premium)
    - "gamma_pptx": Gamma API presentation as PPTX (premium)
    """
    # Use middleware auth as primary, Depends as fallback
    clerk_user_id = getattr(request.state, 'user_id', None)
    if not clerk_user_id and user:
        clerk_user_id = user.get("user_id")

    if not clerk_user_id:
        raise HTTPException(status_code=401, detail="Authentication required")

    # Extract org_id from request state (set by RLS middleware)
    org_id = getattr(request.state, 'org_id', None)

    try:
        # Get internal user ID and fetch message
        pg = await get_postgres_rls_client()
        user_record = await pg.get_user(clerk_user_id)
        if not user_record:
            raise HTTPException(status_code=404, detail="User not found")

        internal_user_id = user_record['id']

        # Fetch the complete message with metadata
        async with pg.acquire_with_org_context(internal_user_id, org_id) as conn:
            message = await conn.fetchrow("""
                SELECT content, metadata, created_at
                FROM chat_messages
                WHERE id = $1 AND role = 'assistant'
            """, message_id)

            if not message:
                raise HTTPException(status_code=404, detail="Message not found")

        # Build message object with all available data
        message_obj = {
            "content": message['content'],
            "metadata": message.get('metadata', {}),
            "created_at": message['created_at'].isoformat() if message['created_at'] else datetime.now().isoformat()
        }

        # Extract structured data from metadata if available
        extras = message_obj['metadata'].get('extras', {})
        charts = message_obj['metadata'].get('charts', [])
        sources = message_obj['metadata'].get('sources', [])

        # Fetch real portfolio data from database
        portfolio_data = await fetch_portfolio_data(internal_user_id, org_id=org_id)
        if not portfolio_data:
            portfolio_data = extras.get('portfolio', None)

        # Determine export format
        export_format = "pptx" if export_type == "gamma_pptx" else "pdf"
        media_type = "application/vnd.openxmlformats-officedocument.presentationml.presentation" if export_format == "pptx" else "application/pdf"
        file_extension = export_format

        logger.info(f"Generating Gamma export: {export_format}")

        # Extract style_name from query parameters (optional)
        style_name = request.query_params.get("style_name")

        # Fetch user export settings (if configured)
        user_settings = await fetch_user_export_style(clerk_user_id, style_name)
        logger.info(f"Fetched user export style for {clerk_user_id[:8]}: {style_name or 'default'}")

        # Determine Gamma format
        gamma_format = "document" if export_format == "pdf" else "presentation"

        # Build natural language instructions from user settings
        # Gamma doesn't accept verbosity/tone/audience as structured params
        # Instead, we inject them as instructions in additionalInstructions
        final_instructions = build_instructions_from_settings(
            base_prompt=user_settings.custom_prompt,
            verbosity=user_settings.verbosity,
            tone=user_settings.tone,
            audience=user_settings.audience
        )

        # Build card options with logo from user settings
        card_options = None
        # Skip logo entirely if it's a blob URL (dev mode) or if source is none
        if user_settings.logo_source != "none":
            # Skip custom logos with blob URLs (can't be used with Gamma API)
            if user_settings.logo_source == "custom" and user_settings.logo_url and user_settings.logo_url.startswith('blob:'):
                # No logo in dev mode with blob URLs
                card_options = None
            else:
                header_footer = {
                    "bottomRight": {"type": "cardNumber"},
                    "hideFromFirstCard": True
                }

                logo_config = {
                    "type": "image",
                    "source": user_settings.logo_source,
                    "size": user_settings.logo_size
                }

                # Add src only if custom logo with valid URL
                if user_settings.logo_source == "custom" and user_settings.logo_url:
                    logo_config["src"] = user_settings.logo_url

                header_footer[user_settings.logo_position] = logo_config
                card_options = {"headerFooter": header_footer}

        # Map verbosity to Gamma's "amount" parameter (Gamma expects: brief, medium, detailed, extensive)
        verbosity_mapping = {
            "brief": "brief",
            "low": "medium",
            "mid": "detailed",
            "high": "extensive"
        }

        # Call Gamma client with user settings
        # Pass complete text_options including language, amount, tone, and audience
        result_bytes = await gamma_client.generate_presentation(
            content=message_obj['content'],
            format=gamma_format,
            export_as=export_format,
            theme_id=user_settings.theme_id,
            text_options={
                "language": user_settings.language,
                "amount": verbosity_mapping.get(user_settings.verbosity, "detailed"),
                "tone": user_settings.tone,
                "audience": user_settings.audience
            },
            additional_instructions=final_instructions,
            cardOptions=card_options
        )

        if not result_bytes:
            raise HTTPException(status_code=500, detail="Failed to generate export. Please try again.")

        # Return document
        filename = f"analysis_{datetime.now().strftime('%Y%m%d')}.{file_extension}"

        return StreamingResponse(
            io.BytesIO(result_bytes),
            media_type=media_type,
            headers={
                "Content-Disposition": f"attachment; filename={filename}"
            }
        )
        
    except HTTPException:
        raise
    except Exception as e:
        logger.exception("Export failed")
        raise HTTPException(status_code=500, detail=str(e))


