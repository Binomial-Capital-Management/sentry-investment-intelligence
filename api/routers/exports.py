async def fetch_portfolio_data(user_id: str, portfolio_id: str = None, org_id: str = None):
    """
    Fetch real portfolio data from database.
    NO HARDCODING - discover portfolio structure dynamically.
    """
    from core.database.postgres_client import get_postgres_rls_client

    try:
        pg = await get_postgres_rls_client()

        # Fetch portfolio data with RLS context
        async with pg.acquire_with_org_context(user_id, org_id) as conn:
            if portfolio_id:
                # Fetch specific portfolio
                portfolio = await conn.fetchrow(
                    "SELECT * FROM portfolios WHERE id = $1",
                    portfolio_id
                )
            else:
                # Fetch default portfolio
                portfolio = await conn.fetchrow(
                    "SELECT * FROM portfolios WHERE is_default = true LIMIT 1"
                )

            if portfolio:
                return {
                    'id': str(portfolio['id']),
                    'name': portfolio['name'],
                    'tickers': portfolio['tickers'],
                    'weights': portfolio['weights'],
                    'value': portfolio.get('value', 1000000),
                    'created_at': portfolio['created_at'].isoformat() if portfolio['created_at'] else None
                }
    except Exception as e:
        logger.warning(f"Failed to fetch portfolio: {e}")

    return None


