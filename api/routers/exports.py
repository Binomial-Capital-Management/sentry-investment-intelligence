@router.post("/markdown-pdf")
async def export_markdown_pdf(request: Request):
    """
    Simple markdown to PDF export with Sentry branding.
    No Gamma API, just Playwright rendering.
    """
    try:
        payload = await request.json()
        markdown = payload.get("content", "")
        title = payload.get("title", "Report")
        
        if not markdown:
            raise HTTPException(status_code=400, detail="content is required")
        
        pdf_bytes = await render_markdown_to_pdf(markdown, title)
        
        filename = f"{title.replace(' ', '_')}_{datetime.now().strftime('%Y%m%d')}.pdf"
        
        return StreamingResponse(
            io.BytesIO(pdf_bytes),
            media_type="application/pdf",
            headers={"Content-Disposition": f"attachment; filename={filename}"}
        )
    except HTTPException:
        raise
    except Exception as e:
        logger.exception("Markdown PDF export failed")
        raise HTTPException(status_code=500, detail=str(e))

