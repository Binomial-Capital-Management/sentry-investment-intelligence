@router.post("/workbook")
async def export_workbook(
    request: Request,
    user = Depends(get_clerk_auth().optional_auth)
):
    """
    Export message as Excel/CSV workbook(s) using Code Interpreter.
    Uses explicit container creation with message_id for non-blocking exports.
    Returns ZIP archive containing generated files.
    """
    logger.info("=== Workbook Export Endpoint Called ===")
    
    clerk_user_id = getattr(request.state, 'user_id', None)
    if not clerk_user_id and user:
        clerk_user_id = user.get("user_id")

    if not clerk_user_id and not config.enable_auth:
        import os
        clerk_user_id = os.getenv('DEV_INTERNAL_USER_ID', 'dev-local-user')
    elif not clerk_user_id:
        logger.error("Authentication failed - no user_id")
        raise HTTPException(status_code=401, detail="Authentication required")

    # Extract org_id from request state (set by RLS middleware)
    org_id = getattr(request.state, 'org_id', None)

    logger.info(f"Authenticated user: {clerk_user_id}")

    try:
        payload = await request.json()
        logger.info(f"Payload received: {list(payload.keys())}")

        # Get internal user ID (skip DB lookup in dev mode)
        if config.enable_postgres and config.enable_auth:
            pg = await get_postgres_rls_client()
            user_record = await pg.get_user(clerk_user_id)
            if not user_record:
                logger.error(f"User not found in DB: {clerk_user_id}")
                raise HTTPException(status_code=404, detail="User not found")

            internal_user_id = user_record['id']
            logger.info(f"Internal user ID: {internal_user_id}")
        else:
            # Dev mode - use clerk_user_id directly
            internal_user_id = clerk_user_id
            logger.info(f"Dev mode - using clerk_user_id as internal_user_id: {internal_user_id}")

        # Prefer direct content if available (works in dev mode, no DB dependency)
        if payload.get("content"):
            logger.info("Using direct content mode")
            import uuid
            message_id = payload.get("message_id") or f"temp_{uuid.uuid4().hex[:12]}"

            content = payload["content"]
            metadata = payload.get("metadata", {})
            extras = metadata.get("extras", {})

            if isinstance(extras, str):
                import json
                extras = json.loads(extras) if extras else {}

            # Only fetch portfolio if PostgreSQL enabled
            portfolio_data = None
            if config.enable_postgres:
                portfolio_data = await fetch_portfolio_data(internal_user_id, org_id=org_id)

            if not portfolio_data:
                portfolio_data = extras.get('portfolio')

            logger.info(f"Content mode: message_id={message_id[:12]}, portfolio={bool(portfolio_data)}")

        # Fallback: Fetch by message_id from database (production mode)
        elif payload.get("message_id") and config.enable_postgres:
            message_id = payload["message_id"]
            logger.info(f"Fetching message from DB: {message_id}")

            pg = await get_postgres_rls_client()
            async with pg.acquire_with_org_context(internal_user_id, org_id) as conn:
                message = await conn.fetchrow("""
                    SELECT content, metadata
                    FROM chat_messages
                    WHERE id = $1 AND role = 'assistant'
                """, message_id)

                if not message:
                    logger.error(f"Message not found: {message_id}")
                    raise HTTPException(status_code=404, detail="Message not found")

            logger.info(f"Message found, content length: {len(message['content'])}")

            content = message['content']
            extras = message.get('metadata', {}).get('extras', {})

            # Parse JSON string extras
            if isinstance(extras, str):
                import json
                extras = json.loads(extras) if extras else {}

            portfolio_data = await fetch_portfolio_data(internal_user_id, org_id=org_id)
            logger.info(f"Portfolio data fetched: {bool(portfolio_data)}")
        
        else:
            logger.error("No message_id or content in payload")
            raise HTTPException(status_code=400, detail="message_id or content required")

        # Generate workbook
        from core.workbook_generator import generate_workbook

        logger.info(f"?? Starting workbook generation for message {message_id}")
        
        zip_bytes = await generate_workbook(
            message_id=message_id,
            content=content,
            extras=extras,
            portfolio=portfolio_data
        )
        
        logger.info(f"? Workbook generation complete: {len(zip_bytes)} bytes")
        
        filename = f"workbooks_{message_id[:8]}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.zip"
        
        return StreamingResponse(
            io.BytesIO(zip_bytes),
            media_type="application/zip",
            headers={"Content-Disposition": f"attachment; filename={filename}"}
        )
            
    except HTTPException as e:
        logger.error(f"HTTPException: {e.status_code} - {e.detail}")
        raise
    except Exception as e:
        logger.exception("Workbook export failed with exception")
        raise HTTPException(status_code=500, detail=str(e))