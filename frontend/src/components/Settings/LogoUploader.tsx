import { useState, useRef } from 'react';
import { Upload, X, Image as ImageIcon } from 'lucide-react';
import { useAuth } from '@clerk/clerk-react';
import axios from 'axios';
import { API_BASE } from '@/services/api';

interface LogoUploaderProps {
  currentLogoUrl: string | null;
  currentFileId: string | null;
  onLogoUploaded: (fileId: string, logoUrl: string) => void;
  onLogoRemoved: () => void;
}

const LogoUploader = ({
  currentLogoUrl,
  currentFileId,
  onLogoUploaded,
  onLogoRemoved,
}: LogoUploaderProps) => {
  const { getToken } = useAuth();
  const [uploading, setUploading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [previewUrl, setPreviewUrl] = useState<string | null>(currentLogoUrl);
  const fileInputRef = useRef<HTMLInputElement>(null);

  const MAX_FILE_SIZE = 5 * 1024 * 1024; // 5MB (conservative limit for logos)
  const ALLOWED_TYPES = ['image/png', 'image/jpeg', 'image/jpg', 'image/svg+xml'];

  const validateFile = (file: File): string | null => {
    if (!ALLOWED_TYPES.includes(file.type)) {
      return 'Please upload a PNG, JPG, or SVG image file.';
    }
    if (file.size > MAX_FILE_SIZE) {
      return `File is too large. Maximum size is ${(MAX_FILE_SIZE / 1024 / 1024).toFixed(0)}MB.`;
    }
    return null;
  };

  const handleFileSelect = async (event: React.ChangeEvent<HTMLInputElement>) => {
    const file = event.target.files?.[0];
    if (!file) return;

    // Validate file
    const validationError = validateFile(file);
    if (validationError) {
      setError(validationError);
      return;
    }

    setError(null);
    setUploading(true);

    try {
      // Create FormData for multipart upload
      const formData = new FormData();
      formData.append('files', file);

      // Upload to backend
      const token = await getToken();
      const response = await axios.post(`${API_BASE}/api/uploads/files`, formData, {
        headers: {
          Authorization: `Bearer ${token}`,
          'Content-Type': 'multipart/form-data',
        },
      });

      if (response.data.status === 'success' && response.data.files.length > 0) {
        const uploadedFile = response.data.files[0];

        // Create preview URL from local file
        const localPreviewUrl = URL.createObjectURL(file);
        setPreviewUrl(localPreviewUrl);

        // Notify parent component with file_id
        // Note: Logo URL will be generated by backend when settings are saved
        onLogoUploaded(uploadedFile.id, localPreviewUrl);
      } else {
        setError('Upload failed. Please try again.');
      }
    } catch (err: any) {
      console.error('Logo upload failed:', err);
      if (err.response?.status === 413) {
        setError('File is too large. Please use a smaller image.');
      } else if (err.response?.data?.detail) {
        setError(err.response.data.detail);
      } else {
        setError('Failed to upload logo. Please try again.');
      }
    } finally {
      setUploading(false);
      // Reset file input
      if (fileInputRef.current) {
        fileInputRef.current.value = '';
      }
    }
  };

  const handleRemove = () => {
    setPreviewUrl(null);
    setError(null);
    onLogoRemoved();
    if (fileInputRef.current) {
      fileInputRef.current.value = '';
    }
  };

  const handleClick = () => {
    fileInputRef.current?.click();
  };

  return (
    <div className="space-y-3">
      {/* Upload Area */}
      <div
        onClick={handleClick}
        className={`
          relative border-2 border-dashed rounded-lg p-6 text-center cursor-pointer
          transition-colors duration-200
          ${uploading ? 'border-gray-300 bg-gray-50 cursor-not-allowed' : 'border-gray-300 hover:border-indigo-400 bg-white'}
          ${error ? 'border-red-300' : ''}
        `}
      >
        <input
          ref={fileInputRef}
          type="file"
          accept="image/png,image/jpeg,image/jpg,image/svg+xml"
          onChange={handleFileSelect}
          disabled={uploading}
          className="hidden"
        />

        {!previewUrl && (
          <div className="space-y-2">
            <div className="flex justify-center">
              <Upload className="h-10 w-10 text-gray-400" />
            </div>
            <div className="text-sm text-gray-600">
              <span className="font-medium text-indigo-600">Click to upload</span> or drag and drop
            </div>
            <p className="text-xs text-gray-500">PNG, JPG, or SVG (max. 5MB)</p>
          </div>
        )}

        {previewUrl && (
          <div className="relative">
            <img
              src={previewUrl}
              alt="Logo preview"
              className="mx-auto max-h-32 rounded"
              onError={() => {
                setPreviewUrl(null);
                setError('Failed to load logo preview');
              }}
            />
            <button
              type="button"
              onClick={(e) => {
                e.stopPropagation();
                handleRemove();
              }}
              className="absolute top-0 right-0 -mt-2 -mr-2 p-1 bg-red-100 rounded-full hover:bg-red-200 transition-colors"
            >
              <X className="h-4 w-4 text-red-600" />
            </button>
          </div>
        )}

        {uploading && (
          <div className="absolute inset-0 flex items-center justify-center bg-white bg-opacity-75 rounded-lg">
            <div className="flex flex-col items-center space-y-2">
              <div className="animate-spin rounded-full h-8 w-8 border-b-2 border-indigo-600"></div>
              <p className="text-sm text-gray-600">Uploading...</p>
            </div>
          </div>
        )}
      </div>

      {/* Error Message */}
      {error && (
        <div className="flex items-start space-x-2 p-3 bg-red-50 border border-red-200 rounded-md">
          <p className="text-sm text-red-800">{error}</p>
        </div>
      )}

      {/* Info */}
      <div className="flex items-start space-x-2 p-3 bg-blue-50 border border-blue-200 rounded-md">
        <ImageIcon className="h-4 w-4 text-blue-600 mt-0.5 flex-shrink-0" />
        <div className="text-xs text-blue-800">
          <p className="font-medium mb-1">Logo Guidelines:</p>
          <ul className="list-disc list-inside space-y-0.5">
            <li>Transparent PNG recommended for best results</li>
            <li>Square or landscape aspect ratio works best</li>
            <li>Minimum 200x200px, maximum 2000x2000px</li>
            <li>Logo will be automatically resized for presentation</li>
          </ul>
        </div>
      </div>
    </div>
  );
};

export default LogoUploader;
